#!/usr/bin/env python3
"""Discover build dependencies and generate Makefiles; never compile or install."""
import argparse
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parent


def run(command, env=None, cwd=None):
    result = subprocess.run(command, env=env, cwd=cwd, text=True, capture_output=True)
    if result.returncode:
        raise RuntimeError(f'{shlex.join(command)} failed:\n{result.stderr.strip()}')
    return result.stdout.strip()


def find_tool(name, candidates=()):
    found = shutil.which(name)
    if found:
        return found
    for candidate in candidates:
        if candidate.is_file() and os.access(candidate, os.X_OK):
            return str(candidate)
    raise RuntimeError(f'{name} not found. Add it to PATH first.')


def discover(args):
    inet = Path(args.inet).expanduser().resolve()
    os3 = Path(args.os3).expanduser().resolve()
    for project, header in [(inet, 'src/inet/common/INETDefs.h'), (os3, 'src/libnorad/cEci.h')]:
        if not (project / header).is_file():
            raise RuntimeError(f'Missing {project / header}; use --inet / --os3 to select dependency checkouts.')
    pkg = find_tool('pkg-config', [Path('/opt/homebrew/bin/pkg-config'), Path('/usr/local/bin/pkg-config')])
    env = os.environ.copy()
    search = [p for p in env.get('PKG_CONFIG_PATH', '').split(os.pathsep) if p]
    brew = shutil.which('brew')
    if not brew:
        brew = next((str(p) for p in (Path('/opt/homebrew/bin/brew'), Path('/usr/local/bin/brew')) if p.is_file()), None)
    if brew:
        for formula in ('igraph', 'curl'):
            result = subprocess.run([brew, '--prefix', formula], text=True, capture_output=True)
            if result.returncode == 0:
                directory = Path(result.stdout.strip()) / 'lib/pkgconfig'
                if directory.is_dir() and str(directory) not in search:
                    search.append(str(directory))
    env['PKG_CONFIG_PATH'] = os.pathsep.join(search)
    try:
        run([pkg, '--exists', 'igraph >= 0.10', 'libcurl'], env)
        cflags = run([pkg, '--cflags', 'igraph', 'libcurl'], env)
        libs = run([pkg, '--libs', 'igraph', 'libcurl'], env)
    except RuntimeError as error:
        raise RuntimeError('igraph (>= 0.10) and libcurl development packages must be visible to pkg-config. '
                           'Install missing packages or set PKG_CONFIG_PATH.\n' + str(error)) from error
    makemake = find_tool('opp_makemake')
    # Generated makefiles use opp_configfilepath; fail early outside setenv.
    find_tool('opp_configfilepath')
    return inet, os3, pkg, env, cflags, libs, makemake


def make_value(value):
    if '\n' in value or '\r' in value:
        raise ValueError('Build paths must not contain newlines')
    return value.replace('$', '$$').replace('#', r'\#')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--inet', default=os.environ.get('INET_ROOT', str(ROOT.parent/'inet4.5')),
                        help='INET project root (default: sibling inet4.5 or INET_ROOT)')
    parser.add_argument('--os3', default=os.environ.get('OS3_ROOT', str(ROOT.parent/'os3')),
                        help='OS3 project root (default: sibling os3 or OS3_ROOT)')
    parser.add_argument('--check', action='store_true', help='Report dependencies without changing files')
    args = parser.parse_args(argv)
    inet, os3, pkg, env, cflags, libs, makemake = discover(args)
    print(f'INET: {inet}\nOS3: {os3}\nCompiler flags: {cflags}\nLinker flags: {libs}')
    if args.check:
        return 0
    # Only machine-specific settings go here. The IDE and CLI both include it.
    command = shlex.join(['env', 'PKG_CONFIG_PATH='+env['PKG_CONFIG_PATH'], pkg])
    settings = ('# Generated by setup.py; local machine settings, not for Git.\n'
                f'LEO_INET_DIR = {make_value(str(inet))}\n'
                f'LEO_OS3_DIR = {make_value(str(os3))}\n'
                f'LEO_PKG_CONFIG_COMMAND = {make_value(command)}\n')
    config = ROOT / 'config.local.mk'
    old = config.read_bytes() if config.exists() else None
    config.write_text(settings)
    try:
        run([makemake, '-f', '--make-so', '--deep', '-o', 'leosatellites'], env, ROOT / 'src')
    except BaseException:
        if old is None:
            config.unlink()
        else:
            config.write_bytes(old)
        raise
    print('Setup complete. Build INET and OS3 first, then run make MODE=release or build in the IDE.')
    return 0


if __name__ == '__main__':
    try:
        raise SystemExit(main())
    except (RuntimeError, ValueError) as error:
        print(f'ERROR: {error}', file=sys.stderr)
        raise SystemExit(1)
